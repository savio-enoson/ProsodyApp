import SwiftUI

// MARK: - CoachingChatView

/// Full-screen coaching view shown after the user finishes a practice session.
///
/// Layout (top → bottom):
///   1. Header with prompt recap and overall scores
///   2. Coach report (streamed) + chat history
///   3. Text input bar for follow-up questions
struct CoachingChatView: View {

    @ObservedObject var coach: CoachingSessionService
    let record: SessionRecord
    @ObservedObject private var tts = TTSManager.shared

    @State private var userInput: String = ""
    @State private var scrollProxy: ScrollViewProxy? = nil
    @Environment(\.dismiss) private var dismiss

    // MARK: - Body

    var body: some View {
        VStack(spacing: 0) {
            header
            Divider()
            chatScrollView
            Divider()
            inputBar
        }
        .frame(minWidth: 640, minHeight: 520)
        .task {
            if coach.reportText.isEmpty && !coach.isGeneratingReport {
                await coach.startReport(record: record)
            }
        }
        .onDisappear {
            tts.stopAllPlayback()
        }
    }

    // MARK: - Header

    private var header: some View {
        VStack(alignment: .leading, spacing: Catalyst.Spacing.space3) {
            HStack(alignment: .top) {
                VStack(alignment: .leading, spacing: Catalyst.Spacing.space1) {
                    Text("Session Review")
                        .font(Catalyst.Typography.title1)
                    if !record.prompt.isEmpty {
                        Text("Prompt: \"\(record.prompt)\"")
                            .font(Catalyst.Typography.caption1)
                            .foregroundColor(.secondary)
                            .lineLimit(2)
                    }
                }
                Spacer()
                HStack(spacing: Catalyst.Spacing.space3) {
                    scoreChip(
                        label: "Pronunciation",
                        score: record.overallPronunciationScore,
                        icon: "mouth.fill"
                    )
                    scoreChip(
                        label: "Fluency",
                        score: record.overallFluencyScore,
                        icon: "waveform"
                    )
                }
                CatalystButton("Done", role: .default) {
                    dismiss()
                }
            }
        }
        .padding(Catalyst.Spacing.space5)
    }

    @ViewBuilder
    private func scoreChip(label: String, score: Int, icon: String) -> some View {
        HStack(spacing: Catalyst.Spacing.space1) {
            Image(systemName: icon)
                .font(.system(size: 11))
                .foregroundColor(.secondary)
            VStack(alignment: .leading, spacing: 0) {
                Text(label)
                    .font(Catalyst.Typography.caption2)
                    .foregroundColor(.secondary)
                Text("\(score)%")
                    .font(Catalyst.Typography.callout)
                    .fontWeight(.semibold)
                    .foregroundColor(scoreColor(score))
            }
        }
        .padding(.horizontal, Catalyst.Spacing.space3)
        .padding(.vertical, Catalyst.Spacing.space2)
        .background(
            RoundedRectangle(cornerRadius: Catalyst.Radius.sm)
                .fill(scoreColor(score).opacity(0.08))
                .overlay(
                    RoundedRectangle(cornerRadius: Catalyst.Radius.sm)
                        .stroke(scoreColor(score).opacity(0.25), lineWidth: 1)
                )
        )
    }

    private func scoreColor(_ score: Int) -> Color {
        score >= 70 ? .green : score >= 45 ? .orange : .red
    }

    // MARK: - Chat Scroll View

    private var chatScrollView: some View {
        ScrollViewReader { proxy in
            ScrollView {
                LazyVStack(alignment: .leading, spacing: Catalyst.Spacing.space4) {

                    // Interactive practice drills generated by action tools
                    interactiveDrillSection
                    fluencyDrillSection

                    // Show streaming report while generating (before it's added to chatHistory)
                    if coach.isGeneratingReport {
                        coachBubble(
                            text: coach.reportText.isEmpty ? "Analysing your session…" : coach.reportText,
                            isStreaming: true
                        )
                        .id("streaming_report")
                    }

                    // Completed chat history (report + follow-ups)
                    ForEach(coach.chatHistory) { message in
                        if message.role == .coach {
                            coachBubble(text: message.text, isStreaming: message.isStreaming)
                                .id(message.id)
                        } else {
                            userBubble(text: message.text)
                                .id(message.id)
                        }
                    }

                    // Generating reply indicator
                    if coach.isGeneratingReply, let last = coach.chatHistory.last, last.role == .coach {
                        // Last message is already being streamed in chatHistory
                        Color.clear.frame(height: 1)
                    }

                    // Error display
                    if let err = coach.reportError {
                        CatalystAlertBanner(.danger, message: err, title: "Coaching unavailable")
                        .padding(.horizontal, Catalyst.Spacing.space2)
                    }

                    // Scroll anchor
                    Color.clear.frame(height: 1).id("bottom")
                }
                .padding(Catalyst.Spacing.space5)
            }
            .onAppear { scrollProxy = proxy }
            .onChange(of: coach.reportText) {
                withAnimation { proxy.scrollTo("bottom", anchor: .bottom) }
            }
            .onChange(of: coach.chatHistory.count) {
                withAnimation { proxy.scrollTo("bottom", anchor: .bottom) }
            }
            .onChange(of: coach.chatHistory.last?.text) {
                withAnimation { proxy.scrollTo("bottom", anchor: .bottom) }
            }
        }
    }

    // MARK: - Message Bubbles

    @ViewBuilder
    private func coachBubble(text: String, isStreaming: Bool) -> some View {
        HStack(alignment: .top, spacing: Catalyst.Spacing.space3) {
            Image(systemName: "person.badge.shield.checkmark.fill")
                .foregroundColor(.accentColor)
                .font(.system(size: 18))
                .padding(.top, 2)

            VStack(alignment: .leading, spacing: Catalyst.Spacing.space2) {
                HStack(spacing: Catalyst.Spacing.space2) {
                    Text("Coach")
                        .font(Catalyst.Typography.caption1)
                        .foregroundColor(.secondary)
                    if isStreaming {
                        ProgressView()
                            .scaleEffect(0.55)
                    }
                }
                Text(LocalizedStringKey(text))
                    .font(Catalyst.Typography.body)
                    .textSelection(.enabled)
                    .frame(maxWidth: .infinity, alignment: .leading)
            }
            .padding(Catalyst.Spacing.space4)
            .background(
                RoundedRectangle(cornerRadius: Catalyst.Radius.md)
                    .fill(Color.secondary.opacity(0.06))
                    .overlay(
                    RoundedRectangle(cornerRadius: Catalyst.Radius.md)
                        .stroke(Color.secondary.opacity(0.12), lineWidth: 1)
                )
            )
        }
    }

    @ViewBuilder
    private func userBubble(text: String) -> some View {
        HStack(alignment: .top, spacing: Catalyst.Spacing.space3) {
            Spacer(minLength: 60)

            Text(text)
                .font(Catalyst.Typography.body)
                .padding(Catalyst.Spacing.space4)
                .background(
                    RoundedRectangle(cornerRadius: Catalyst.Radius.md)
                        .fill(Color.accentColor.opacity(0.12))
                        .overlay(
                            RoundedRectangle(cornerRadius: Catalyst.Radius.md)
                                .stroke(Color.accentColor.opacity(0.25), lineWidth: 1)
                        )
                )

            Image(systemName: "person.fill")
                .foregroundColor(.accentColor)
                .font(.system(size: 18))
                .padding(.top, 2)
        }
    }

    // MARK: - Input Bar

    private var inputBar: some View {
        HStack(spacing: Catalyst.Spacing.space3) {
            TextField(
                "Ask the coach a question…",
                text: $userInput,
                axis: .vertical
            )
            .lineLimit(1...4)
            .font(Catalyst.Typography.body)
            .textFieldStyle(.plain)
            .padding(Catalyst.Spacing.space3)
            .background(
                RoundedRectangle(cornerRadius: Catalyst.Radius.sm)
                    .fill(Color.secondary.opacity(0.06))
                    .overlay(
                        RoundedRectangle(cornerRadius: Catalyst.Radius.sm)
                            .stroke(Color.secondary.opacity(0.2), lineWidth: 1)
                    )
            )
            .disabled(coach.isGeneratingReport || coach.isGeneratingReply)
            .onSubmit { sendMessage() }

            CatalystButton("Send", role: .primary) {
                sendMessage()
            }
            .disabled(
                userInput.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
                || coach.isGeneratingReport
                || coach.isGeneratingReply
            )
        }
        .padding(Catalyst.Spacing.space4)
    }

    // MARK: - Interactive Drill Deck

    @ViewBuilder
    private var interactiveDrillSection: some View {
        if !coach.activeDrills.isEmpty {
            CatalystPanel {
                VStack(alignment: .leading, spacing: Catalyst.Spacing.space3) {
                    HStack {
                        Label("Pronunciation Lab & Interactive Drills", systemImage: "waveform.badge.mic")
                            .font(Catalyst.Typography.headline)
                        Spacer()
                        CatalystBadge("\(coach.activeDrills.count) active drill\(coach.activeDrills.count == 1 ? "" : "s")", variant: .success)
                    }

                    Text("The AI Coach generated targeted drills and Golden Speaker demos based on your acoustics:")
                        .font(Catalyst.Typography.caption1)
                        .foregroundColor(.secondary)

                    VStack(spacing: Catalyst.Spacing.space3) {
                        ForEach(coach.activeDrills) { drill in
                            drillCardView(drill)
                        }
                    }
                }
            }
        }
    }

    // MARK: - Fluency Drill Deck

    @ViewBuilder
    private var fluencyDrillSection: some View {
        if !coach.activeFluencyDrills.isEmpty {
            CatalystPanel {
                VStack(alignment: .leading, spacing: Catalyst.Spacing.space3) {
                    HStack {
                        Label("Rhythm & Pacing Lab", systemImage: "metronome")
                            .font(Catalyst.Typography.headline)
                        Spacer()
                        CatalystBadge("\(coach.activeFluencyDrills.count) pacing drill\(coach.activeFluencyDrills.count == 1 ? "" : "s")", variant: .primary)
                    }

                    Text("Pacing and phrase-linking exercises synthesized at target speaking tempo:")
                        .font(Catalyst.Typography.caption1)
                        .foregroundColor(.secondary)

                    VStack(spacing: Catalyst.Spacing.space3) {
                        ForEach(coach.activeFluencyDrills) { drill in
                            fluencyDrillCardView(drill)
                        }
                    }
                }
            }
        }
    }

    @ViewBuilder
    private func fluencyDrillCardView(_ drill: FluencyDrillCard) -> some View {
        let isPlayingThis = tts.isPlayingCustom && (drill.audioURL != nil && tts.activeCustomURL?.path == drill.audioURL?.path)

        VStack(alignment: .leading, spacing: Catalyst.Spacing.space2) {
            HStack(alignment: .center, spacing: Catalyst.Spacing.space2) {
                Text(drill.targetPhrase)
                    .font(Catalyst.Typography.headline)
                    .fontWeight(.bold)
                    .foregroundColor(.primary)

                CatalystBadge(String(format: "%.1fx Speed", drill.targetSpeed), variant: .teal)

                Spacer()

                if drill.isSynthesizing {
                    HStack(spacing: 4) {
                        ProgressView().scaleEffect(0.6).frame(width: 14, height: 14)
                        Text("Synthesizing...")
                            .font(Catalyst.Typography.caption2)
                            .foregroundColor(.secondary)
                    }
                } else if drill.audioURL != nil {
                    CatalystButton(
                        isPlayingThis ? "Stop" : "Hear at Target Pace",
                        role: isPlayingThis ? .danger : .primary
                    ) {
                        if isPlayingThis {
                            tts.stopCustomAudio()
                        } else {
                            coach.playFluencyDrillAudio(drill)
                        }
                    }
                }
            }

            if !drill.pacingTip.isEmpty {
                HStack(alignment: .top, spacing: Catalyst.Spacing.space2) {
                    Image(systemName: "lightbulb.fill")
                        .font(.system(size: 11))
                        .foregroundColor(.orange)
                        .padding(.top, 2)
                    Text(drill.pacingTip)
                        .font(Catalyst.Typography.caption1)
                        .foregroundColor(.secondary)
                }
            }
        }
        .padding(Catalyst.Spacing.space3)
        .background(
            RoundedRectangle(cornerRadius: Catalyst.Radius.sm)
                .fill(Color.secondary.opacity(0.04))
                .overlay(
                    RoundedRectangle(cornerRadius: Catalyst.Radius.sm)
                        .stroke(Color.secondary.opacity(0.12), lineWidth: 1)
                )
        )
    }

    @ViewBuilder
    private func drillCardView(_ drill: InteractiveDrillCard) -> some View {
        let isPlayingThis = tts.isPlayingCustom && (drill.audioURL != nil && tts.activeCustomURL?.path == drill.audioURL?.path)

        VStack(alignment: .leading, spacing: Catalyst.Spacing.space2) {
            HStack(alignment: .center, spacing: Catalyst.Spacing.space2) {
                Text(drill.targetWord)
                    .font(Catalyst.Typography.title3)
                    .fontWeight(.bold)
                    .foregroundColor(.primary)

                if let phoneme = drill.focusPhoneme, !phoneme.isEmpty {
                    CatalystBadge("/\(phoneme)/", variant: .primary)
                }

                if let contrast = drill.contrastWord, !contrast.isEmpty {
                    CatalystBadge("Contrast: \(contrast)", variant: .warning)
                }

                Spacer()

                if drill.isSynthesizing {
                    HStack(spacing: 4) {
                        ProgressView().scaleEffect(0.6).frame(width: 14, height: 14)
                        Text("Cloning...")
                            .font(Catalyst.Typography.caption2)
                            .foregroundColor(.secondary)
                    }
                } else if drill.audioURL != nil || coach.generatedClips[drill.targetWord.lowercased()] != nil {
                    CatalystButton(
                        isPlayingThis ? "Stop" : "Hear in My Voice",
                        role: isPlayingThis ? .danger : .primary
                    ) {
                        if isPlayingThis {
                            tts.stopCustomAudio()
                        } else {
                            coach.playDrillAudio(drill)
                        }
                    }
                }
            }

            if !drill.practiceSentence.isEmpty {
                HStack(alignment: .top, spacing: Catalyst.Spacing.space2) {
                    Image(systemName: "quote.opening")
                        .font(.system(size: 11))
                        .foregroundColor(.secondary)
                        .padding(.top, 2)
                    Text(drill.practiceSentence)
                        .font(Catalyst.Typography.body)
                        .italic()
                        .foregroundColor(.primary)
                }
                .padding(Catalyst.Spacing.space2)
                .frame(maxWidth: .infinity, alignment: .leading)
                .background(Color.secondary.opacity(0.04))
                .cornerRadius(Catalyst.Radius.sm)
            }

            if let tip = drill.articulatoryTip, !tip.isEmpty {
                HStack(alignment: .top, spacing: Catalyst.Spacing.space2) {
                    Image(systemName: "lightbulb.fill")
                        .font(.system(size: 11))
                        .foregroundColor(.orange)
                        .padding(.top, 2)
                    Text(tip)
                        .font(Catalyst.Typography.caption1)
                        .foregroundColor(.secondary)
                }
            }
        }
        .padding(Catalyst.Spacing.space3)
        .background(
            RoundedRectangle(cornerRadius: Catalyst.Radius.sm)
                .fill(Color.secondary.opacity(0.04))
                .overlay(
                    RoundedRectangle(cornerRadius: Catalyst.Radius.sm)
                        .stroke(Color.secondary.opacity(0.12), lineWidth: 1)
                )
        )
    }

    // MARK: - Actions

    private func sendMessage() {
        let text = userInput.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !text.isEmpty else { return }
        userInput = ""
        Task { await coach.sendUserMessage(text) }
    }
}
